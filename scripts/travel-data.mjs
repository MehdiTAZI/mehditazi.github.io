// One language-neutral browser dataset, shared by both language pages.
export function runtimeTravelData(data) {
    return Object.fromEntries(Object.entries(data).map(([code, record]) => {
        if (code === '_meta') return [code, record];
        const { country, photos, ...shared } = record;
        return [code, { ...shared, photos: (photos || []).map(({ src }) => ({ src })) }];
    }));
}

export function travelScript(data) {
    return `/* Generated from travel-albums.json. Do not edit this file directly. */\nwindow.TRAVEL_ALBUMS = ${JSON.stringify(runtimeTravelData(data))};\n`;
}
